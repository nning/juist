#!/bin/sh
# Points /etc/resolv.conf at the file juistd writes, where systemd-resolved
# does not run, keeping the host's own beside it, or gives the host's back.
# juistd then answers the host's DNS on 53 itself: the network's names, and
# everything else from the host's own resolvers. tailscaled's is left alone:
# it would take it back and ask juistd's resolver in turn. So is every
# resolv.conf where the owner turned juist's DNS off (juist set --dns=false).
#
#   resolv.sh start | stop [INSTANCE]
#
# juistd.service runs it as root before juistd starts and after it stops. An
# instance's, given INSTANCE, leaves resolv.conf to the default instance.
set -u
root=${JUIST_RESOLV_ROOT:-}
conf=$root/etc/resolv.conf
own=$root/run/juist/resolv.conf
saved=$root/etc/resolv.pre-juist.conf
nm=$root/run/NetworkManager/resolv.conf
tailscaleds=$root/etc/resolv.pre-tailscale-backup.conf
dnsoff=$root/var/lib/juist/dns-off

[ -z "${2:-}" ] || exit 0

ours() { [ "$(readlink "$conf" 2>/dev/null)" = "$own" ]; }

# link NAME TARGET replaces NAME by a link to TARGET at once.
link() { ln -sfn "$2" "$1.juist-new" && mv -f "$1.juist-new" "$1"; }

# giveback NAME puts the host's own in NAME, a link to juistd's.
giveback() {
	if [ -L "$saved" ]; then
		link "$1" "$(readlink "$saved")"
	elif [ -f "$saved" ]; then
		cp -p "$saved" "$1.juist-new" && mv -f "$1.juist-new" "$1"
	else
		echo "resolv.sh: $saved, the host's own resolv.conf, is gone; $1 still names juistd's" >&2
		return 1
	fi
}

case ${1:-} in
start)
	if [ -e "$dnsoff" ]; then
		ours && { giveback "$conf" || exit 1; }
		rm -f "$saved"
		exit 0
	fi
	if ! ours; then
		systemctl is-active --quiet systemd-resolved 2>/dev/null && exit 0
		case $(readlink "$conf" 2>/dev/null) in
		*/run/systemd/resolve/*) exit 0 ;;
		esac
		grep -qs "generated by tailscale" "$conf" && exit 0
		[ -d "$(dirname "$own")" ] || exit 0
		if [ -L "$conf" ]; then
			link "$saved" "$(readlink "$conf")" || exit 1
		elif [ -f "$conf" ] && [ -f "$nm" ] && cmp -s "$conf" "$nm"; then
			# NetworkManager's, which it keeps writing there once
			# resolv.conf is a link elsewhere.
			link "$saved" "$nm" || exit 1
		elif [ -f "$conf" ]; then
			cp -p "$conf" "$saved.juist-new" && mv -f "$saved.juist-new" "$saved" || exit 1
		else
			exit 0
		fi
	fi
	if [ ! -e "$saved" ]; then
		echo "resolv.sh: $saved, the host's own resolv.conf, is gone" >&2
		exit 1
	fi
	# The host's own until juistd writes its own.
	link "$own" "$saved" || exit 1
	ours || link "$conf" "$own"
	;;
stop)
	ours && { giveback "$conf" || exit 1; }
	# tailscaled took resolv.conf back, keeping juistd's as the host's own.
	if [ "$(readlink "$tailscaleds" 2>/dev/null)" = "$own" ]; then
		giveback "$tailscaleds" || exit 1
	fi
	rm -f "$saved"
	;;
*)
	echo "usage: resolv.sh start | stop [INSTANCE]" >&2
	exit 2
	;;
esac
