// resolv.sh hands /etc/resolv.conf to juistd where systemd-resolved does not
// run, with juistd's file the host's own until juistd writes it, keeps it so
// across a restart, and gives the host's back as it was, a link as a link;
// NetworkManager's, which it goes on writing, is followed. Where resolved runs
// and for an instance it does nothing, and where DNS is off it gives the
// host's back.
func TestResolvScriptHandsResolvConfToJuistdAndBack(t *testing.T) {
	script, err := filepath.Abs("resolv.sh")
	if err != nil {
		t.Fatal(err)
	}
	type host struct{ root, conf, own, saved string }
	setup := func(t *testing.T) (host, func(args ...string) string) {
		sb := newSandbox(t)
		h := host{root: sb.root, conf: filepath.Join(sb.root, "etc/resolv.conf"),
			own: filepath.Join(sb.root, "run/juist/resolv.conf"), saved: filepath.Join(sb.root, "etc/resolv.pre-juist.conf")}
		for _, d := range []string{"etc", "run/juist", "run/NetworkManager"} {
			os.MkdirAll(filepath.Join(sb.root, d), 0o755)
		}
		return h, func(args ...string) string {
			t.Helper()
			cmd := exec.Command("/bin/sh", append([]string{script}, args...)...)
			cmd.Env = []string{"PATH=" + filepath.Join(sb.root, "bin") + ":/usr/bin:/bin", "JUIST_RESOLV_ROOT=" + sb.root}
			out, err := cmd.CombinedOutput()
			if err != nil {
				t.Fatalf("resolv.sh %v: %v\n%s", args, err, out)
			}
			return string(out)
		}
	}
	link := func(t *testing.T, path string) string {
		t.Helper()
		l, err := os.Readlink(path)
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		return l
	}
	read := func(path string) string { b, _ := os.ReadFile(path); return string(b) }
	const lan = "nameserver 192.168.1.1\nsearch lan\n"

	t.Run("a file", func(t *testing.T) {
		h, run := setup(t)
		os.WriteFile(h.conf, []byte(lan), 0o644)
		run("start", "")
		if link(t, h.conf) != h.own || link(t, h.own) != h.saved || read(h.saved) != lan || read(h.conf) != lan {
			t.Fatalf("started, resolv.conf reads %q", read(h.conf))
		}
		// Written by juistd, then started again after a crash, which
		// leaves its file the host's own again.
		os.Remove(h.own)
		os.WriteFile(h.own, []byte("nameserver fd00::1\n"), 0o644)
		run("start", "")
		if link(t, h.own) != h.saved || read(h.saved) != lan {
			t.Fatalf("started again, the host's own reads %q", read(h.saved))
		}
		run("stop", "")
		if fi, err := os.Lstat(h.conf); err != nil || !fi.Mode().IsRegular() || read(h.conf) != lan {
			t.Errorf("stopped, resolv.conf reads %q (%v)", read(h.conf), err)
		}
		if _, err := os.Lstat(h.saved); !os.IsNotExist(err) {
			t.Errorf("stopped, the host's own stays: %v", err)
		}
	})
	t.Run("a link", func(t *testing.T) {
		h, run := setup(t)
		target := filepath.Join(h.root, "run/resolvconf/resolv.conf")
		os.MkdirAll(filepath.Dir(target), 0o755)
		os.WriteFile(target, []byte(lan), 0o644)
		os.Symlink(target, h.conf)
		run("start", "")
		if link(t, h.conf) != h.own || link(t, h.saved) != target || read(h.conf) != lan {
			t.Fatalf("started, resolv.conf reads %q", read(h.conf))
		}
		run("stop", "")
		if link(t, h.conf) != target {
			t.Errorf("stopped, resolv.conf links to %s", link(t, h.conf))
		}
	})
	t.Run("NetworkManager's", func(t *testing.T) {
		h, run := setup(t)
		nm := filepath.Join(h.root, "run/NetworkManager/resolv.conf")
		os.WriteFile(nm, []byte(lan), 0o644)
		os.WriteFile(h.conf, []byte(lan), 0o644)
		run("start", "")
		if link(t, h.saved) != nm {
			t.Errorf("started, the host's own is not NetworkManager's: %s", link(t, h.saved))
		}
	})
	t.Run("resolved", func(t *testing.T) {
		h, run := setup(t)
		os.WriteFile(h.conf, []byte(lan), 0o644)
		os.WriteFile(filepath.Join(h.root, "active"), []byte("systemd-resolved\n"), 0o644)
		run("start", "")
		run("stop", "")
		if fi, err := os.Lstat(h.conf); err != nil || !fi.Mode().IsRegular() {
			t.Errorf("with resolved, resolv.conf was touched: %v", err)
		}
	})
	const tailscaleds = "# resolv.conf(5) file generated by tailscale\nnameserver 100.100.100.100\n"
	t.Run("tailscaled's", func(t *testing.T) {
		h, run := setup(t)
		os.WriteFile(h.conf, []byte(tailscaleds), 0o644)
		run("start", "")
		if fi, err := os.Lstat(h.conf); err != nil || !fi.Mode().IsRegular() || read(h.conf) != tailscaleds {
			t.Errorf("tailscaled's resolv.conf was touched: %v", err)
		}
		if _, err := os.Lstat(h.saved); !os.IsNotExist(err) {
			t.Errorf("the host's own was kept: %v", err)
		}
	})
	t.Run("taken back by tailscaled", func(t *testing.T) {
		h, run := setup(t)
		backup := filepath.Join(h.root, "etc/resolv.pre-tailscale-backup.conf")
		os.WriteFile(h.conf, []byte(lan), 0o644)
		run("start", "")
		if err := os.Rename(h.conf, backup); err != nil {
			t.Fatal(err)
		}
		os.WriteFile(h.conf, []byte(tailscaleds), 0o644)
		run("stop", "")
		if fi, err := os.Lstat(backup); err != nil || !fi.Mode().IsRegular() || read(backup) != lan {
			t.Errorf("stopped, tailscaled's backup reads %q (%v)", read(backup), err)
		}
		if read(h.conf) != tailscaleds {
			t.Errorf("stopped, resolv.conf reads %q", read(h.conf))
		}
	})
	t.Run("DNS off", func(t *testing.T) {
		h, run := setup(t)
		os.WriteFile(h.conf, []byte(lan), 0o644)
		run("start", "")
		if link(t, h.conf) != h.own {
			t.Fatal("not taken while DNS is on")
		}
		os.MkdirAll(filepath.Join(h.root, "var/lib/juist"), 0o700)
		os.WriteFile(filepath.Join(h.root, "var/lib/juist/dns-off"), nil, 0o600)
		run("start", "")
		if fi, err := os.Lstat(h.conf); err != nil || !fi.Mode().IsRegular() || read(h.conf) != lan {
			t.Errorf("DNS off, resolv.conf stays juistd's: %v", err)
		}
		if _, err := os.Lstat(h.saved); !os.IsNotExist(err) {
			t.Errorf("DNS off, the host's own stays beside it: %v", err)
		}
	})
	t.Run("an instance", func(t *testing.T) {
		h, run := setup(t)
		os.WriteFile(h.conf, []byte(lan), 0o644)
		run("start", "juist1")
		if fi, err := os.Lstat(h.conf); err != nil || !fi.Mode().IsRegular() {
			t.Errorf("an instance touched resolv.conf: %v", err)
		}
	})
}

// Programs AppArmor confines resolve names through its nameservice
// abstraction, which names the files resolv.conf may link to; the package
// adds the one resolv.sh links it to, or they resolve nothing.
func TestAppArmorLetsConfinedProgramsReadJuistdsResolvConf(t *testing.T) {
	sh, err := os.ReadFile("resolv.sh")
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`(?m)^own=\$root(\S+)$`).FindSubmatch(sh)
	if m == nil {
		t.Fatal("resolv.sh names no own=")
	}
	snippet, err := os.ReadFile("apparmor/juist")
	if err != nil {
		t.Fatal(err)
	}
	if rule := string(m[1]) + " r,"; !slices.Contains(strings.Split(string(snippet), "\n"), rule) {
		t.Errorf("apparmor/juist lacks %q", rule)
	}
	mk, err := os.ReadFile("../Makefile")
	if err != nil {
		t.Fatal(err)
	}
	const dst = "/etc/apparmor.d/abstractions/nameservice.d/juist"
	if !strings.Contains(string(mk), "packaging/apparmor/juist $$root"+dst+";") {
		t.Errorf("make deb does not install apparmor/juist as %s", dst)
	}
	if !regexp.MustCompile(`printf[^>]*` + regexp.QuoteMeta(dst) + `[^>]*> \$\$root/DEBIAN/conffiles`).Match(mk) {
		t.Errorf("%s is not among the .deb's conffiles", dst)
	}
}

// postinst reloads AppArmor where it is enabled, once for each snippet it has
// not loaded, and a purge forgets which it loaded.
func TestPostinstReloadsAppArmorForANewSnippet(t *testing.T) {
	sb := newSandbox(t)
	snippet := filepath.Join(sb.root, "etc/apparmor.d/abstractions/nameservice.d/juist")
	os.MkdirAll(filepath.Dir(snippet), 0o755)
	b, err := os.ReadFile("apparmor/juist")
	if err != nil {
		t.Fatal(err)
	}
	os.WriteFile(snippet, b, 0o644)
	const reload = "systemctl reload apparmor.service\n"

	sb.run("postinst", "configure", "0.9")
	if calls := sb.calls(); strings.Contains(calls, reload) {
		t.Fatalf("postinst reloaded AppArmor where it is not enabled:\n%s", calls)
	}
	os.MkdirAll(filepath.Join(sb.root, "sys/kernel/security/apparmor"), 0o755)
	sb.run("postinst", "configure", "0.9")
	if calls := sb.calls(); !strings.Contains(calls, reload) {
		t.Fatalf("postinst did not reload AppArmor for a new snippet:\n%s", calls)
	}
	sb.run("postinst", "configure", "0.9")
	if calls := sb.calls(); strings.Contains(calls, reload) {
		t.Fatalf("postinst reloaded AppArmor for a snippet it had loaded:\n%s", calls)
	}
	os.WriteFile(snippet, append(b, "/run/juist/other r,\n"...), 0o644)
	sb.run("postinst", "configure", "0.9")
	if calls := sb.calls(); !strings.Contains(calls, reload) {
		t.Fatalf("postinst did not reload AppArmor for a changed snippet:\n%s", calls)
	}
	sb.run("postrm", "purge")
	if _, err := os.Stat(filepath.Join(sb.root, "var/lib/juist.apparmor")); err == nil {
		t.Fatal("a purge left the marker of the loaded snippet")
	}
}

// Where resolv.conf is juistd's, Debian's dhclient-script, which writes what
// readlink -f names, writes the host's own beside it, never juistd's;
// elsewhere resolv.conf as before.
func TestDHClientWritesTheHostsOwnBesideJuistds(t *testing.T) {
	hook, err := filepath.Abs("dhclient/juist")
	if err != nil {
		t.Fatal(err)
	}
	// make_resolv_conf's way of writing, in dhclient-script's shell.
	const dhclient = `. "$1"
resolv_conf=$(readlink -f "$JUIST_RESOLV_ROOT/etc/resolv.conf" 2>/dev/null) || resolv_conf="$JUIST_RESOLV_ROOT/etc/resolv.conf"
echo "nameserver 10.0.0.9" > "$resolv_conf.dhclient-new"
cat "$resolv_conf.dhclient-new" > "$resolv_conf"
rm -f "$resolv_conf.dhclient-new"
readlink "$JUIST_RESOLV_ROOT/etc/resolv.conf" || true`
	const renewed, juistds, lan = "nameserver 10.0.0.9\n", "nameserver fd00::1\n", "nameserver 192.168.1.1\n"
	setup := func(t *testing.T) (root, conf, own, saved string) {
		root = t.TempDir()
		for _, d := range []string{"etc", "run/juist"} {
			os.MkdirAll(filepath.Join(root, d), 0o755)
		}
		return root, filepath.Join(root, "etc/resolv.conf"), filepath.Join(root, "run/juist/resolv.conf"),
			filepath.Join(root, "etc/resolv.pre-juist.conf")
	}
	renew := func(t *testing.T, root string) string {
		t.Helper()
		cmd := exec.Command("/bin/sh", "-c", dhclient, "dhclient-script", hook)
		cmd.Env = []string{"PATH=/usr/bin:/bin", "JUIST_RESOLV_ROOT=" + root}
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("dhclient-script: %v\n%s", err, out)
		}
		return strings.TrimSpace(string(out))
	}
	read := func(path string) string { b, _ := os.ReadFile(path); return string(b) }

	t.Run("juistd's", func(t *testing.T) {
		root, conf, own, saved := setup(t)
		os.WriteFile(saved, []byte(lan), 0o644)
		os.WriteFile(own, []byte(juistds), 0o644)
		os.Symlink(own, conf)
		if l := renew(t, root); l != own {
			t.Errorf("readlink without -f says %q, want %q", l, own)
		}
		if read(saved) != renewed || read(own) != juistds {
			t.Errorf("renewed, the host's own reads %q and juistd's %q", read(saved), read(own))
		}
	})
	t.Run("the host's", func(t *testing.T) {
		root, conf, _, _ := setup(t)
		os.WriteFile(conf, []byte(lan), 0o644)
		renew(t, root)
		if read(conf) != renewed {
			t.Errorf("renewed, resolv.conf reads %q", read(conf))
		}
	})
}
