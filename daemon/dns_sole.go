// A soleResolver is a host resolver that asks juistd's resolver alone, on
// port 53, for every name, as a resolv.conf without domains or ports does:
// juistd answers the network's names and asks the host's own resolvers the
// rest.
type soleResolver interface {
	HostDNS
	// hostResolv is the host's own resolvers and search domains, juistd's
	// aside.
	hostResolv() resolvConf
}

// resolvConf is what a resolv.conf says.
type resolvConf struct {
	servers []netip.AddrPort
	search  []string
	options []string
}

func parseResolvConf(b []byte) resolvConf {
	var c resolvConf
	for _, l := range strings.Split(string(b), "\n") {
		f := strings.Fields(l)
		if len(f) < 2 {
			continue
		}
		switch f[0] {
		case "nameserver":
			if a, err := netip.ParseAddr(f[1]); err == nil && a.Zone() == "" {
				c.servers = append(c.servers, netip.AddrPortFrom(a.Unmap(), 53))
			}
		case "search", "domain":
			// The last of them counts.
			c.search = slices.Clone(f[1:])
		case "options":
			c.options = append(c.options, strings.Join(f[1:], " "))
		}
	}
	return c
}

// searchWith is ours first, then the host's, each once.
func searchWith(ours, host []string) []string {
	out := slices.Clone(ours)
	for _, s := range host {
		s = strings.TrimSuffix(strings.ToLower(s), ".")
		if s != "" && !slices.Contains(out, s) {
			out = append(out, s)
		}
	}
	return out
}

// OwnResolvConf is the resolv.conf juistd writes where the package's resolv.sh
// pointed /etc/resolv.conf at it, and SavedResolvConf the host's own, which
// resolv.sh keeps there and gives back.
var (
	OwnResolvConf   = "/run/juist/resolv.conf"
	SavedResolvConf = "/etc/resolv.pre-juist.conf"
)

// resolvConfIsOwn reports whether path is a link to OwnResolvConf.
func resolvConfIsOwn(path string) bool {
	l, err := os.Readlink(path)
	return err == nil && l == OwnResolvConf
}

// tailscaledWrote reports whether tailscaled wrote the resolv.conf at path,
// which resolv.sh leaves to it.
func tailscaledWrote(path string) bool {
	b, err := os.ReadFile(path)
	return err == nil && bytes.Contains(b, []byte("generated by tailscale"))
}

// fileDNS is the host's DNS by OwnResolvConf, where no systemd-resolved runs:
// juistd's resolver alone while it routes, the host's own otherwise. redirect
// takes the host's own queries on 53 to the port each server answers on.
type fileDNS struct {
	own, saved string
	redirect   func([]netip.AddrPort) error
}

const fileHeader = "# Written by juistd: the host's own is " // + saved

func (f fileDNS) Route(rt DNSRouting) error {
	if !rt.Everything {
		return errNoDomains
	}
	host := f.hostResolv()
	var b bytes.Buffer
	b.WriteString(fileHeader + f.saved + "\n")
	for _, s := range rt.Servers {
		fmt.Fprintf(&b, "nameserver %s\n", s.Addr())
	}
	if s := searchWith(rt.Search, host.search); len(s) > 0 {
		fmt.Fprintf(&b, "search %s\n", strings.Join(s, " "))
	}
	for _, o := range host.options {
		fmt.Fprintf(&b, "options %s\n", o)
	}
	// Before resolv.conf names them, lest a lookup go to a port nothing
	// answers on.
	if err := f.redirect(rt.Servers); err != nil {
		return err
	}
	tmp := f.own + ".new"
	os.Remove(tmp)
	if err := os.WriteFile(tmp, b.Bytes(), 0o644); err != nil {
		return err
	}
	// Readable by every program, whatever juistd's umask.
	if err := os.Chmod(tmp, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, f.own)
}

// Revert links OwnResolvConf to the host's own, which it then follows.
func (f fileDNS) Revert() error {
	if l, err := os.Readlink(f.own); err != nil || l != f.saved {
		tmp := f.own + ".new"
		os.Remove(tmp)
		if err := os.Symlink(f.saved, tmp); err != nil {
			return err
		}
		if err := os.Rename(tmp, f.own); err != nil {
			return err
		}
	}
	return f.redirect(nil)
}

func (fileDNS) routesDomains() bool { return true }

func (f fileDNS) hostResolv() resolvConf {
	b, _ := os.ReadFile(f.saved)
	return parseResolvConf(b)
}

func (f fileDNS) through(path string, servers []netip.AddrPort) (bool, string) {
	if l, err := os.Readlink(path); err != nil || l != f.own {
		if tailscaledWrote(path) {
			return false, "tailscaled writes " + path
		}
		return false, path + " is no longer juistd's"
	}
	return asksOnly(path, servers, "juistd")
}

// resolvconfDNS is plumbedDNS where juistd's resolver answers the host:
// resolvconf takes it for juist's device alone, and the other interfaces'
// resolvers are the host's own.
type resolvconfDNS struct{ plumbedDNS }

func (resolvconfDNS) routesDomains() bool { return true }

// on53 says juistd's resolver must answer on 53, which resolvconf names
// alone.
func (resolvconfDNS) on53() bool { return true }

func (r resolvconfDNS) Route(rt DNSRouting) error {
	rt.Search = searchWith(rt.Search, r.hostResolv().search)
	return r.plumbedDNS.Route(rt)
}

// Resolvconf is resolvconf(8), which lists each interface's resolv.conf.
var Resolvconf = "/sbin/resolvconf"

// fromInterface opens each interface's part of resolvconf -l.
var fromInterface = regexp.MustCompile(`(?m)^# resolv\.conf from (\S+)$`)

func (r resolvconfDNS) hostResolv() resolvConf {
	out, err := exec.Command(Resolvconf, "-l").Output()
	if err != nil {
		return resolvConf{}
	}
	var c resolvConf
	parts := fromInterface.FindAllSubmatchIndex(out, -1)
	for i, m := range parts {
		if devicePattern.Match(out[m[2]:m[3]]) {
			continue
		}
		end := len(out)
		if i+1 < len(parts) {
			end = parts[i+1][0]
		}
		p := parseResolvConf(out[m[1]:end])
		c.servers = append(c.servers, p.servers...)
		c.search = searchWith(c.search, p.search)
		c.options = append(c.options, p.options...)
	}
	return c
}

// devicePattern is juist's devices, whose resolvers are juistd's.
var devicePattern = regexp.MustCompile(`^juist[0-9]$`)

func (r resolvconfDNS) through(path string, servers []netip.AddrPort) (bool, string) {
	return asksOnly(path, servers, "juistd")
}

// asksOnly reports whether the resolv.conf at path asks servers alone, who
// are whom, and why not.
func asksOnly(path string, servers []netip.AddrPort, whom string) (bool, string) {
	got, why := nameservers(path)
	if why != "" {
		return false, why
	}
	for _, s := range got {
		if !slices.ContainsFunc(servers, func(ap netip.AddrPort) bool { return ap.Addr().String() == s }) {
			return false, path + " asks " + s + ", not " + whom
		}
	}
	return true, ""
}

// soleUpstream is the host's own resolvers, which juistd's resolver asks
// where the host asks it alone; read again after hostRoutingEvery. Never
// tailscaled's, which take juistd's for theirs once tailscaled has
// resolv.conf back, nor juistd's own; the last found where none is left.
func (d *Daemon) soleUpstream(s soleResolver) []netip.AddrPort {
	d.soleMu.Lock()
	defer d.soleMu.Unlock()
	if d.soleReadAt.IsZero() || d.now().Sub(d.soleReadAt) >= hostRoutingEvery || d.now().Before(d.soleReadAt) {
		d.soleReadAt = d.now()
		ups := withoutTailscaled(s.hostResolv().servers)
		if len(ups) == 0 {
			ups = withoutTailscaled(dnsfwd.ResolversIn(PreTailscaleResolvConf))
		}
		ups = slices.DeleteFunc(ups, func(a netip.AddrPort) bool { return a.Addr() == d.soleOwn })
		if len(ups) > 0 {
			d.soleServers = ups
		}
	}
	return slices.Clone(d.soleServers)
}

// soleAnswersAt has soleUpstream leave out at, where juistd's resolver
// answers.
func (d *Daemon) soleAnswersAt(at netip.Addr) {
	d.soleMu.Lock()
	defer d.soleMu.Unlock()
	if d.soleOwn != at {
		d.soleOwn, d.soleReadAt = at, time.Time{}
	}
}
